/**
 * Draws the shop pipeline's sample delivery photo (a wind-up T-rex in its box with a battery pack
 * that should not be there) as a PNG and writes it as base64 to src/pipelines/shop/sample-photo.ts.
 *
 *   npx tsx scripts/shop-make-sample-photo.ts
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { deflateSync } from "node:zlib";

const W = 320;
const H = 220;
type RGB = [number, number, number];
const px = new Uint8Array(W * H * 3);

function hex(c: string): RGB {
  const n = Number.parseInt(c.replace("#", ""), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function set(x: number, y: number, c: RGB): void {
  if (x < 0 || y < 0 || x >= W || y >= H) return;
  const i = (Math.floor(y) * W + Math.floor(x)) * 3;
  px[i] = c[0];
  px[i + 1] = c[1];
  px[i + 2] = c[2];
}

function rect(x0: number, y0: number, w: number, h: number, c: RGB): void {
  for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) set(x, y, c);
}

function ellipse(cx: number, cy: number, rx: number, ry: number, c: RGB): void {
  for (let y = Math.floor(cy - ry); y <= cy + ry; y++) {
    for (let x = Math.floor(cx - rx); x <= cx + rx; x++) {
      const dx = (x - cx) / rx;
      const dy = (y - cy) / ry;
      if (dx * dx + dy * dy <= 1) set(x, y, c);
    }
  }
}

function line(x0: number, y0: number, x1: number, y1: number, c: RGB, width = 2): void {
  const steps = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0));
  for (let s = 0; s <= steps; s++) {
    const t = steps === 0 ? 0 : s / steps;
    rect(Math.round(x0 + (x1 - x0) * t), Math.round(y0 + (y1 - y0) * t), width, width, c);
  }
}

// Box interior and flaps.
rect(0, 0, W, H, hex("#b88a4f"));
rect(14, 14, W - 28, H - 28, hex("#d9b47a"));
rect(14, 14, W - 28, 6, hex("#c59c61"));

// Wind-up T-rex (tin, green) on the left.
const green = hex("#3f7d4e");
const dark = hex("#2c5a38");
ellipse(105, 120, 52, 30, green); // body
ellipse(160, 82, 26, 18, green); // head
rect(140, 92, 22, 22, green); // neck
ellipse(52, 132, 34, 10, green); // tail
rect(82, 140, 14, 34, dark); // back leg
rect(118, 140, 14, 34, dark); // front leg
rect(78, 170, 22, 6, dark);
rect(114, 170, 22, 6, dark);
rect(150, 108, 14, 5, dark); // tiny arm
ellipse(168, 76, 3, 3, hex("#fbf8f1")); // eye
ellipse(168, 76, 1.5, 1.5, hex("#1b2a41"));
line(150, 92, 182, 92, dark, 2); // mouth
// Brass wind-up key on the back.
const brass = hex("#c9a227");
rect(98, 82, 6, 12, brass);
ellipse(92, 78, 8, 6, brass);
ellipse(110, 78, 8, 6, brass);

// Battery pack (3 x AA in a black holder) on the right.
rect(206, 98, 86, 64, hex("#262626"));
for (let i = 0; i < 3; i++) {
  const x = 214 + i * 26;
  rect(x, 106, 20, 48, hex("#3a3a3a"));
  rect(x, 106, 20, 14, hex("#c47a2c"));
  rect(x + 7, 101, 6, 6, hex("#b0b0b0")); // positive nub
  rect(x + 8, 128, 4, 12, hex("#fbf8f1")); // plus sign
  rect(x + 4, 132, 12, 4, hex("#fbf8f1"));
}
// Motor unit with red and black wires.
rect(232, 176, 34, 22, hex("#5b5b5b"));
line(240, 162, 240, 176, hex("#b3261e"), 3);
line(258, 162, 258, 176, hex("#1b1b1b"), 3);

// PNG encode (RGB, filter 0 per row).
const raw = Buffer.alloc((W * 3 + 1) * H);
for (let y = 0; y < H; y++) {
  raw[y * (W * 3 + 1)] = 0;
  Buffer.from(px.subarray(y * W * 3, (y + 1) * W * 3)).copy(raw, y * (W * 3 + 1) + 1);
}

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf: Buffer): number {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(W, 0);
ihdr.writeUInt32BE(H, 4);
ihdr[8] = 8; // bit depth
ihdr[9] = 2; // RGB
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk("IHDR", ihdr),
  chunk("IDAT", deflateSync(raw, { level: 9 })),
  chunk("IEND", Buffer.alloc(0)),
]);

const out = path.join(process.cwd(), "src/pipelines/shop/sample-photo.ts");
const b64 = png.toString("base64");
const lines = b64.match(/.{1,100}/g) ?? [];
writeFileSync(
  out,
  [
    "/**",
    " * Sample delivery photo: the wind-up T-rex in its box with a 3 x AA battery pack and a motor unit.",
    " * Generated by scripts/shop-make-sample-photo.ts. Do not edit by hand.",
    " */",
    'export const SAMPLE_PHOTO_CONTENT_TYPE = "image/png" as const;',
    "",
    "export const SAMPLE_PHOTO_BASE64 = [",
    ...lines.map((l) => `  "${l}",`),
    '].join("");',
    "",
  ].join("\n"),
);
console.log(`Wrote ${out} (${png.length} bytes PNG, ${b64.length} chars base64)`);
